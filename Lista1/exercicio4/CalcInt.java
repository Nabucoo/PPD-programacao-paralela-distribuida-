package exercicio4;

public class CalcInt {

    static int soma(int a, int b) {
        return a + b;
    }

    static int subtracao(int a, int b) {
        return a - b;
    }

    static int multiplicacao(int a, int b) {
        return  a * b;
    }

    static double divisao(int a, int b) {
        return a / b;
    }

    static int resto(int a, int b) {
        return a % b;
    }
}
