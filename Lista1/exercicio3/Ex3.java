package exercicio3;

public class Ex3{ 
    public static void main(String[] args) {
        byte numerobyte = 122;
        short numeroshort = 200;
        int numeroint = 10000000;
        long numerolong = 1098765678L;
        float numerofloat = 3.14f;
        double numerodouble = 3.14158d;
        char letrachar = 'a';
        boolean simounao = true;
        String frasseString = "Bom dia!!!";

        System.out.println("Tipo: byte | " + numerobyte);
        System.out.println("Tipo: short | " + numeroshort);
        System.out.println("Tipo: int | " + numeroint);
        System.out.println("Tipo: long | " + numerolong);
        System.out.println("Tipo: float | " + numerofloat);
        System.out.println("Tipo: double | " + numerodouble);
        System.out.println("Tipo: char | " + letrachar);
        System.out.println("Tipo: boolean | " + simounao);
        System.out.println("Tipo: String | " + frasseString);
        
    }

}