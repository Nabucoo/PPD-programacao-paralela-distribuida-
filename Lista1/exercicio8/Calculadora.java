package exercicio8;

public class Calculadora {

    int somar(int a, int b) {
        return a + b;
    }

    int subtrair(int a, int b) {
        return a - b;
    }

    int multiplicar(int a, int b) {
        return  a * b;
    }

    double dividir(double a, double b) {
        return a / b;
    }
}
